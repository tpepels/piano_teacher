"""Authentic reusable tie contours engraved once by Verovio.

The native UI must not invent a tie curve. This extracts ONLY Verovio's
tapered tie object from a small, actual tied-note MusicXML example. Godot
maps the engraving's source notehead centres to its fixed musical beat
coordinates; the ink is generated by Verovio, never a hand-built polygon.
"""
from __future__ import annotations

import base64
from functools import lru_cache
from io import BytesIO
import math
import xml.etree.ElementTree as ET

from PIL import Image

TIE_ATLAS_VERSION = 1
DIVISIONS = 10080


def _score_xml(stem: str) -> str:
    return f"""<?xml version="1.0" encoding="utf-8"?>
<score-partwise version="4.0"><work><work-title> </work-title></work>
<movement-title> </movement-title><part-list><score-part id="P1">
<part-name>Piano</part-name></score-part></part-list>
<part id="P1"><measure number="1"><attributes>
<divisions>{DIVISIONS}</divisions><time><beats>4</beats>
<beat-type>4</beat-type></time><clef><sign>G</sign>
<line>2</line></clef></attributes>
<note id="tie-first"><pitch><step>B</step><octave>4</octave></pitch>
<duration>{DIVISIONS*2}</duration><type>half</type><stem>{stem}</stem>
<tie type="start"/><notations><tied type="start"/></notations></note>
<note id="tie-last"><pitch><step>B</step><octave>4</octave></pitch>
<duration>{DIVISIONS*2}</duration><type>half</type><stem>{stem}</stem>
<tie type="stop"/><notations><tied type="stop"/></notations></note>
</measure></part></score-partwise>"""


def _extract_tie(svg: str) -> str:
    root = ET.fromstring(svg)
    ns = "{http://www.w3.org/2000/svg}"
    tie = next((node for node in root.iter()
                if "tie" in node.get("class", "").split()), None)
    if tie is None:
        raise RuntimeError("Verovio engraving has no genuine tie SVG group")

    def trim(node: ET.Element) -> bool:
        if node is tie:
            # Do not include layout-only diagnostic rectangle paths.
            for parent in node.iter():
                for child in list(parent):
                    if "bounding-box" in child.get("class", "").split() or (
                            "content-bounding-box" in child.get("class", "").split()):
                        parent.remove(child)
            return True
        if node.tag in {ns+"defs", ns+"style"}:
            return True
        remaining = False
        for child in list(node):
            if trim(child):
                remaining = True
            else:
                node.remove(child)
        return remaining
    if not trim(root):
        raise RuntimeError("Verovio tie object was not inside SVG document")
    return ET.tostring(root, encoding="unicode")


def _render(toolkit, direction: str) -> dict:
    import cairosvg
    from .score_geometry import parse_svg_geometry
    if not toolkit.loadData(_score_xml(direction)):
        raise RuntimeError("Verovio refused tied-note MusicXML")
    svg = toolkit.renderToSVG(1)
    geometry = parse_svg_geometry(svg)
    if not {"tie-first", "tie-last"}.issubset(geometry.elements):
        raise RuntimeError("Missing tie notehead anchor positions")
    x0, y0, system = geometry.elements["tie-first"]
    x1, _, _ = geometry.elements["tie-last"]
    rails = geometry.staff_systems[system]["staff_lines"]
    if x1 <= x0 or len(rails) < 5:
        raise RuntimeError("Invalid Verovio tie anchor or staff geometry")
    svg = _extract_tie(svg)
    png = cairosvg.svg2png(bytestring=svg.encode(), output_width=1600)
    with Image.open(BytesIO(png)) as im:
        image = im.convert("RGBA")
    staff_px = (rails[1]-rails[0])*image.height
    if staff_px <= 3:
        raise RuntimeError("Invalid Verovio staff-space for tie engraving")
    bounds = image.getchannel("A").getbbox()
    if not bounds:
        raise RuntimeError("Verovio tie did not produce an ink contour")
    left, top, right, bottom = bounds
    origin_x = x0*image.width
    origin_y = y0*image.height
    crop = image.crop(bounds)
    tintable = Image.new("RGBA",crop.size,(255,255,255,255))
    tintable.putalpha(crop.getchannel("A"))
    encoded = BytesIO()
    tintable.save(encoded,format="PNG",optimize=True)
    box = [(left-origin_x)*250/staff_px,(top-origin_y)*250/staff_px,
           (right-left)*250/staff_px,(bottom-top)*250/staff_px]
    span = (x1-x0)*image.width*250/staff_px
    if not all(math.isfinite(v) for v in box+[span]) or span <= 0:
        raise RuntimeError("Non-finite genuine tie bounds")
    return {"source":"verovio-engraved-tie",
            "units_per_space":250, "bounds":box,"span":span,
            "png_base64":base64.b64encode(encoded.getvalue()).decode("ascii")}


@lru_cache(maxsize=2)
def _generate(font: str) -> dict:
    import verovio
    from .score import _create_verovio_toolkit
    toolkit = _create_verovio_toolkit(verovio)
    if not toolkit.setOptions({"inputFrom":"xml","scale":48,
            "pageWidth":900,"pageHeight":650,"adjustPageHeight":True,
            "svgViewBox":True,"svgBoundingBoxes":True,
            "svgContentBoundingBoxes":True}):
        raise RuntimeError("Verovio rejected genuine tie template options")
    return {direction:_render(toolkit,direction) for direction in ("up","down")}


def tie_templates(cache=None) -> dict:
    import verovio
    from .notation_symbols import native_glyphs
    font = native_glyphs()["head_black"]["font"]
    version = getattr(verovio,"__version__","unknown")
    key = cache.key("verovio-ties",TIE_ATLAS_VERSION,font,version) if cache else None
    if key:
        saved = cache.read_json("verovio-ties",key)
        if (isinstance(saved,dict) and set(saved)=={"up","down"}
                and all(isinstance(x,dict) and
                        x.get("source")=="verovio-engraved-tie" and
                        x.get("span",0)>0 for x in saved.values())):
            return saved
    result = _generate(font)
    if key:
        cache.write_json("verovio-ties",key,result)
    return result
