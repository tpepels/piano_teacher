#!/usr/bin/env python3
"""Write godot/state_contract.gd from piano_teacher/state_contract.py.

Usage: generate_state_contract.py [--check]
--check exits 1 if the committed GDScript differs from the Python contract.
"""
from __future__ import annotations

from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from piano_teacher import state_contract  # noqa: E402

TARGET = ROOT / "godot" / "state_contract.gd"


def render() -> str:
    rows = "\n".join(
        f'    "{key}": [{", ".join(repr(kind).replace(chr(39), chr(34)) for kind in kinds)}],'
        for key, kinds in sorted(state_contract.SCHEMA.items()))
    static = ", ".join(f'"{key}"' for key in state_contract.STATIC_KEYS)
    return f'''extends RefCounted
## GENERATED by scripts/generate_state_contract.py from
## piano_teacher/state_contract.py. Do not edit by hand.
## The versioned contract of the per-frame state snapshot.

const VERSION := {state_contract.VERSION}
const STATIC_KEYS := [{static}]
const SCHEMA := {{
{rows}
}}

static func kind_of(value: Variant) -> String:
    match typeof(value):
        TYPE_NIL:
            return "null"
        TYPE_BOOL:
            return "bool"
        TYPE_INT, TYPE_FLOAT:
            return "number"
        TYPE_STRING, TYPE_STRING_NAME:
            return "string"
        TYPE_ARRAY:
            return "list"
        TYPE_DICTIONARY:
            return "dict"
    return type_string(typeof(value))

## Contract violations of one snapshot (empty when it conforms).
static func problems(state: Dictionary) -> Array[String]:
    var found: Array[String] = []
    if int(state.get("schema_version", -1)) != VERSION:
        found.append("schema_version %s, expected %d" % [
            str(state.get("schema_version")), VERSION])
    for key in state:
        if not SCHEMA.has(key):
            found.append("unknown key '%s'" % key)
        elif kind_of(state[key]) not in SCHEMA[key]:
            found.append("'%s' is %s, expected %s" % [
                key, kind_of(state[key]), "|".join(SCHEMA[key])])
    return found
'''


def main() -> int:
    text = render()
    if "--check" in sys.argv[1:]:
        if not TARGET.exists() or TARGET.read_text() != text:
            print(f"{TARGET} is out of date; run scripts/generate_state_contract.py",
                  file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
